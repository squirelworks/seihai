/// Glyph rows for `c`. Characters outside printable ASCII show as `?`.
pub fn glyph(c: char) -> &'static [u8; 7] {
    let i = c as u32;
    if (0x20..0x7F).contains(&i) {
        &GLYPHS[(i - 0x20) as usize]
    } else {
        &GLYPHS[(b'?' - 0x20) as usize]
    }
}

/// Width in pixels of `text` drawn with [`glyph`].
pub fn text_width(text: &str) -> i32 {
    text.chars().count() as i32 * CELL_W
}
