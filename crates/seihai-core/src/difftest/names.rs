fn lookup(table: &[(u8, &'static str)], id: u32) -> Option<&'static str> {
    let id = u8::try_from(id).ok()?;
    table.iter().find(|(i, _)| *i == id).map(|(_, n)| *n)
}

/// `PLI_*` name of a client-to-server id, without the prefix.
pub fn pli_name(id: u32) -> Option<&'static str> {
    lookup(PLI, id)
}

/// `PLO_*` name of a server-to-client id, without the prefix.
pub fn plo_name(id: u32) -> Option<&'static str> {
    lookup(PLO, id)
}

/// `PLPROP_*` name of a player property id, without the prefix.
pub fn prop_name(id: u32) -> Option<&'static str> {
    lookup(PLPROP, id)
}
