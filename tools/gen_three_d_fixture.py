#!/usr/bin/env python3
"""Regenerate seihai-core's three_d_toml.tsv from Graal_analysis version-profiles/three-d.toml.

usage: tools/gen_three_d_fixture.py PATH/TO/Graal_analysis > PATH/TO/seihai-core/crates/seihai-core/src/protocol/three_d_toml.tsv

The TSV is the per-build Torque 3D side (`VersionProfile::three_d`) in the same columns and
spelling as `three_d::fixture_row` in seihai-core; that crate's unit tests compare every profile
with it. Graal_analysis is the source of truth: change three-d.toml there, then rerun this.

A [[build]] with `base = "<label>"` takes that build's values; its own keys override them. Its
`evidence` table may say `all = "assumed"` and then name the fields that are read. Every field must
have a value and an evidence tag (bin, lab, cap, assumed, or several of the first three); a field is
assumed when its tag is exactly "assumed". Needs Python 3.11 (tomllib).
"""
import sys, tomllib
from pathlib import Path

FIELDS = [
    'protocol', 'game', 'class_table', 'class_ids_12bit', 'length_prefixes', 'game_layer',
    'mission_phases', 'phases_optional', 'client_moves', 'control_objects', 'ter_file', 'ter_max',
    'terrain_chunks', 'chunk_cache', 'terrain_texture', 'water', 'torque_script', 'server_scripts', 'terraformer',
    'terrain_editor', 'dts_min', 'dts_max', 'dif_version', 'three_ds', 'md3_version', 'texture_names',
    'download_refused', 'bigdata', 'bigdata_chunk_max', 'terrain_chunk_max', 'udp_port_offset',
]
CHOICES = {
    'class_table': {0, 3, 2},
    'game_layer': {'tge', 'gameobject'},
    'chunk_cache': {'none', 'heights'},
    'torque_script': {'compiles', 'none'},
    'terraformer': {'full', 'greyscale', 'none'},
    'texture_names': {'strip_png', 'as_named'},
}
CONTROL = {'Player', 'Camera', 'GameObject'}
TAGS = {'bin', 'lab', 'cap'}
META = {'label', 'platform', 'base', 'why', 'evidence'}

doc = tomllib.load(open(Path(sys.argv[1]) / 'version-profiles/three-d.toml', 'rb'))
by_label = {}
rows = []
for b in doc['build']:
    unknown = set(b) - set(FIELDS) - META
    if unknown:
        raise SystemExit(f"{b['label']}: unknown keys {sorted(unknown)}")
    vals = dict(by_label[b['base']]) if 'base' in b else {}
    vals.update({k: v for k, v in b.items() if k in FIELDS})
    missing = [f for f in FIELDS if f not in vals]
    if missing:
        raise SystemExit(f"{b['label']}: no value for {missing}")
    for k, allowed in CHOICES.items():
        if vals[k] not in allowed:
            raise SystemExit(f"{b['label']}: {k} = {vals[k]!r} not in {sorted(map(str, allowed))}")
    if not set(vals['control_objects']) <= CONTROL:
        raise SystemExit(f"{b['label']}: control_objects {vals['control_objects']}")
    ev = dict(b['evidence'])
    default = ev.pop('all', None)
    bad = set(ev) - set(FIELDS)
    if bad:
        raise SystemExit(f"{b['label']}: evidence for unknown fields {sorted(bad)}")
    assumed = []
    for f in FIELDS:
        tag = ev.get(f, default)
        if tag is None:
            raise SystemExit(f"{b['label']}: no evidence for {f}")
        words = tag.split()
        if words == ['assumed']:
            assumed.append(f)
        elif not words or not set(words) <= TAGS:
            raise SystemExit(f"{b['label']}: evidence {f} = {tag!r}")
    by_label[b['label']] = vals
    rows.append((b['label'], vals, assumed))

b = lambda v: '1' if v else '0'
print('# generated by tools/gen_three_d_fixture.py from Graal_analysis version-profiles/three-d.toml; do not edit')
print('# label\t' + '\t'.join(FIELDS) + '\tassumed')
for label, v, assumed in rows:
    cols = [
        label, str(v['protocol']), v['game'], str(v['class_table']), b(v['class_ids_12bit']),
        b(v['length_prefixes']), v['game_layer'], str(v['mission_phases']), b(v['phases_optional']),
        b(v['client_moves']), ','.join(v['control_objects']), b(v['ter_file']), str(v['ter_max']),
        b(v['terrain_chunks']), v['chunk_cache'], v['terrain_texture'] or '-', b(v['water']),
        v['torque_script'], b(v['server_scripts']), v['terraformer'], b(v['terrain_editor']), str(v['dts_min']), str(v['dts_max']),
        str(v['dif_version']), b(v['three_ds']), str(v['md3_version']), v['texture_names'],
        ','.join(v['download_refused']) or '-', b(v['bigdata']), str(v['bigdata_chunk_max']),
        str(v['terrain_chunk_max']), str(v['udp_port_offset']),
        'all' if len(assumed) == len(FIELDS) else (','.join(assumed) or '-'),
    ]
    print('\t'.join(cols))
