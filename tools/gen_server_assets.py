def sfx(rng, rate, ms, tone=None, noise=0.0, cutoff=0.3, attack=0.004, decay=12.0, trem=0.0):
    """One synthesised effect. tone: (start Hz, end Hz) of a sine sweep;
    noise: share of low-passed noise; decay: exponential decay per second."""
    n = int(rate * ms / 1000)
    y, phase, out = 0.0, 0.0, []
    for i in range(n):
        t = i / rate
        env = min(1.0, t / attack) * math.exp(-t * decay)
        if trem:
            env *= 0.6 + 0.4 * math.sin(2 * math.pi * trem * t)
        s = 0.0
        if tone:
            f = tone[0] + (tone[1] - tone[0]) * (i / n)
            phase += 2 * math.pi * f / rate
            s += (1 - noise) * math.sin(phase)
        if noise:
            y += cutoff * (rng.uniform(-1, 1) - y)
            s += noise * y * 2.4
        out.append(max(-1.0, min(1.0, s * env * 0.8)))
    return out


def seq(*parts):
    out = []
    for p in parts:
        out += p
    return out


