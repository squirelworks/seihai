# basepackage.gupd: every 4.x to 6.x build asks for it first. A minimal
# GRPKG001 with NAME, VERSION, PLATFORM and MODE is accepted
# (Graal_analysis protocol/v5v6-lab-play.md; keys from v4x-clients.md). It
# lists no FILE lines: what the clients do with a package's files is still
# open (protocol/update-packages-focus-status.md).
BASEPACKAGE = "GRPKG001\nNAME basepackage\nVERSION 1.0\nPLATFORM any\nMODE required\n"


def save_variant(im, pal, path, bits, size, clear=0):
    D.save_png(im.copy(), pal, path, bits, size, True, clear)


def write_all(out):
    for sub in ("images", "bodies", "heads", "swords", "shields", "ganis", "sounds", "packages"):
        os.makedirs(os.path.join(out, sub), exist_ok=True)

    # The default set, regenerated, then copied into the server layout.
    with tempfile.TemporaryDirectory() as tmp:
        D.write_all(tmp)
        for rel, dst in ((("pics1.png",), "images"), (("sprites.png",), "images"), (("state.png",), "images"),
                         (("tiledefs.txt",), "images")):
            shutil.copyfile(os.path.join(tmp, *rel), os.path.join(out, dst, rel[-1]))
        for f in sorted(os.listdir(os.path.join(tmp, "gani"))):
            shutil.copyfile(os.path.join(tmp, "gani", f), os.path.join(out, "ganis", f))
        for f in sorted(os.listdir(os.path.join(tmp, "sounds"))):
            shutil.copyfile(os.path.join(tmp, "sounds", f), os.path.join(out, "sounds", f))

    im, pal = D.build_sword()
    for name, look in SWORD_LOOKS:
        q = pal
        if look:
            q = shifted(pal, ())
            for n, rgb in zip(("blade", "blade_dk", "hilt"), look):
                q.rgb[q.names.index(n)] = rgb
        save_variant(im, q, os.path.join(out, "swords", name), 4, 16)
    im, pal = D.build_shield()
    for name, hue, sat, val in SHIELD_LOOKS:
        q = shifted(pal, ("shield", "shield_dk", "shield_lt"), hue, sat, val) if hue else pal
        save_variant(im, q, os.path.join(out, "shields", name), 4, 16)
    im, pal = D.build_body()
    for name, hue in BODY_LOOKS:
        q = shifted(pal, [n for n in pal.names if n not in ("outline", "skin", "clear")], hue) if hue else pal
        save_variant(im, q, os.path.join(out, "bodies", name), 4, 16, D.BODY_CLEAR)
    im, pal = D.build_head()
    for name, hue in HEAD_LOOKS:
        q = shifted(pal, [n for n in pal.names if n not in ("clear", "outline", "eye", "eye_white")], hue) if hue else pal
        save_variant(im, q, os.path.join(out, "heads", name), 4, 16)
    for folder in ("bodies", "heads", "swords", "shields"):
        for f in sorted(os.listdir(os.path.join(out, folder))):
            if f.endswith(".png"):
                D.save_gif_copy(os.path.join(out, folder, f))

    for name, build in (("chest.png", build_chest), ("wbowi1.png", build_bow_icon), ("wbomb1.png", build_bomb_icon)):
        if name == "chest.png":
            build().save(os.path.join(out, "images", name), "PNG", optimize=True, compress_level=9)
        else:
            im, p = build()
            D.save_png(im, p, os.path.join(out, "images", name), 4, 16, True)
            D.save_gif_copy(os.path.join(out, "images", name))

    for name, fn in EXTRA_GANIS.items():
        open(os.path.join(out, "ganis", name + ".gani"), "w", newline="\n").write(fn())

    for name, (rate, bits, samples) in sounds(random.Random(SEED)).items():
        D.write_wav(os.path.join(out, "sounds", name + ".wav"), rate, bits, samples)

    open(os.path.join(out, "packages", "basepackage.gupd"), "w", newline="\n").write(BASEPACKAGE)


def copy_fonts(out, src):
    dst = os.path.join(out, FONTS)
    os.makedirs(dst, exist_ok=True)
    for name, source in FONT_FILES.items():
        shutil.copyfile(os.path.join(src, source), os.path.join(dst, name))


def listing(root):
    return [f for f in D.listing(root) if not f.startswith(FONTS + os.sep) and f != "README.md"]


def check(out):
    with tempfile.TemporaryDirectory() as tmp:
        write_all(tmp)
        want, have = listing(tmp), listing(out)
        bad = [f"missing {f}" for f in want if f not in have] + [f"extra {f}" for f in have if f not in want]
        bad += [f"differs {f}" for f in want if f in have and not D.same(os.path.join(tmp, f), os.path.join(out, f))]
    fonts = os.path.join(out, FONTS)
    bad += [f"missing {FONTS}/{n}" for n in FONT_FILES if not os.path.exists(os.path.join(fonts, n))]
    for b in bad:
        print(b, file=sys.stderr)
    return not bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(ROOT, "assets", "server"))
    ap.add_argument("--check", action="store_true", help="regenerate to a temp dir and compare with --out")
    ap.add_argument("--fonts", metavar="DIR", help="copy Liberation Sans from DIR under the client font names")
    a = ap.parse_args()
    if a.check:
        ok = check(a.out)
        print("assets/server is up to date" if ok else "assets/server differs from the generator", file=sys.stderr)
        return 0 if ok else 1
    write_all(a.out)
    if a.fonts:
        copy_fonts(a.out, a.fonts)
    files = D.listing(a.out)
    total = sum(os.path.getsize(os.path.join(a.out, f)) for f in files)
    print(f"wrote {len(files)} files, {total} bytes, to {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
