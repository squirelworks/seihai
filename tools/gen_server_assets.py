def build_chest():
    """chest.png, 32x32: a closed chest, for NPCs that use it as their image."""
    pal = D.sheet_palette()
    im = D.chest_img(pal, False)
    im.putpalette(pal.flat(256))
    grass = pal["grass"]
    rgba = im.convert("RGB").convert("RGBA")
    px = [(0, 0, 0, 0) if im.getpixel((x, y)) == grass else rgba.getpixel((x, y))
          for y in range(32) for x in range(32)]
    rgba.putdata(px)
    return rgba


def icon_palette():
    p = D.Pal(transparent=True)
    for n, c in [("ink", (32, 28, 40)), ("wood", (150, 96, 48)), ("wood_lt", (210, 150, 84)),
                 ("string", (236, 236, 220)), ("steel", (200, 204, 216)), ("bomb", (48, 60, 96)),
                 ("bomb_lt", (110, 130, 190)), ("fuse", (190, 150, 90)), ("spark", (255, 214, 64)),
                 ("spark2", (255, 120, 40))]:
        p.add(n, c)
    return p


def build_bow_icon():
    """wbowi1.png, 32x32: the bow's icon in the weapon list."""
    p = icon_palette()
    im = Image.new("P", (32, 32), 0)
    d = ImageDraw.Draw(im)
    d.arc([4, 3, 26, 29], 290, 70, fill=p["ink"], width=5)
    d.arc([5, 4, 25, 28], 290, 70, fill=p["wood"], width=3)
    d.arc([6, 5, 24, 27], 300, 60, fill=p["wood_lt"], width=1)
    d.line([(21, 5), (21, 27)], fill=p["string"])
    d.line([(6, 16), (26, 16)], fill=p["wood"], width=1)
    d.polygon([(26, 16), (22, 13), (22, 19)], fill=p["steel"], outline=p["ink"])
    d.line([(4, 14), (7, 16), (4, 18)], fill=p["string"])
    return im, p


def build_bomb_icon():
    """wbomb1.png, 32x32: the bomb's icon in the weapon list."""
    p = icon_palette()
    im = Image.new("P", (32, 32), 0)
    d = ImageDraw.Draw(im)
    d.ellipse([5, 9, 27, 31], fill=p["bomb"], outline=p["ink"])
    d.ellipse([10, 13, 15, 18], fill=p["bomb_lt"])
    d.rectangle([13, 6, 19, 10], fill=p["ink"])
    d.line([(16, 6), (18, 3), (21, 2)], fill=p["fuse"], width=2)
    for x, y, c in ((23, 1, "spark"), (25, 3, "spark2"), (22, 0, "spark2"), (24, 2, "spark")):
        d.point((x, y), fill=p[c])
    return im, p


# ---------------------------------------------------------------------------
# More player animations: the names the 2.x to 6.x clients ask for in play
# (push, pull, grab, lift, spin, hidden, hiddenstill; Graal_analysis
# protocol/v5v6-lab-play.md "Play: what the client does"). Built from the
# body poses of the default sheet; the steps and timing are Seihai's own.
# ---------------------------------------------------------------------------

LEAN = [(0, -2), (-2, 0), (0, 2), (2, 0)]  # toward the facing side
BUSH = "SPRITE 30 SPRITES 0 338 32 32 bush over the player"


def player_row(dr, pose, dx=0, dy=0, head=True):
    (sx, sy), (bx, by), (hx, hy) = D.OFFSETS[dr]
    parts = [f"0 {sx} {sy}", f"{200 + 4 * pose + dr} {bx + dx} {by + dy}"]
    if head:
        parts.append(f"{100 + dr} {hx + dx} {hy + dy}")
    return ", ".join(parts)


def gani(title, poses, steps, flags=(), extra=(), setback=None):
    L = D.gani_header(title)
    L += list(flags)
    if setback:
        L.append(f"SETBACKTO {setback}")
    L += ["DEFAULTHEAD head0.png", "DEFAULTBODY body.png", ""]
    L += D.gani_sprites(poses, extra) + ["", "ANI"]
    for rows, tail in steps:
        L += rows
        L += tail
        L.append("")
    L += ["ANIEND", ""]
    return D.with_hats("\n".join(L))


def push_gani():
    steps = []
    for k in range(8):
        pose = 1 + (k // 2) % 8 * 2 % 8  # slow steps: 1 3 5 7 ...
        rows = [player_row(dr, pose, *LEAN[dr]) for dr in range(D.DIRS)]
        steps.append((rows, ["WAIT 1"] + (["PLAYSOUND steps2.wav 1.5 2"] if k in (0, 4) else [])))
    return gani("push.gani: leaning into a wall or block, slow steps", range(1, 9), steps, ["LOOP", "CONTINUOUS"])


def pull_gani():
    steps = []
    for k in range(8):
        pose = 8 - (k % 8)
        rows = [player_row(dr, pose, -LEAN[dr][0], -LEAN[dr][1]) for dr in range(D.DIRS)]
        steps.append((rows, ["WAIT 1"]))
    return gani("pull.gani: leaning back and pulling, slow steps backwards", range(1, 9), steps, ["LOOP", "CONTINUOUS"])


def grab_gani():
    rows = [player_row(dr, D.POSE_WINDUP, *LEAN[dr]) for dr in range(D.DIRS)]
    return gani("grab.gani: holding on to a wall or block (1 step)", [D.POSE_WINDUP], [(rows, [])])


def lift_gani():
    steps = []
    for k, (pose, dy) in enumerate(((D.POSE_SIT, 4), (D.POSE_SIT, 2), (D.POSE_CARRY_STILL, 0))):
        steps.append(([player_row(dr, pose, 0, dy) for dr in range(D.DIRS)], ["WAIT 1"]))
    return gani("lift.gani: bending down and lifting an object (3 steps)",
                [D.POSE_SIT, D.POSE_CARRY_STILL], steps, setback="carrystill")


def spin_gani():
    """The spin attack: the player turns once round, sword held out in each
    direction in turn (clockwise from the facing side), two ticks each."""
    sprites = []
    for dr, n in enumerate(("up", "left", "down", "right")):
        sprites.append(f"SPRITE {304 + dr} SWORD {32 * dr} 32 32 32 sword arc {n}")
    steps = []
    order = [0, 3, 2, 1]  # up, right, down, left: clockwise
    for k in range(8):
        rows = []
        for dr in range(D.DIRS):
            f = order[(order.index(dr) + k // 2) % 4]
            (sx, sy), (bx, by), (hx, hy) = D.OFFSETS[f]
            hand = D.HAND[D.POSE_SWING][f]
            pv = D.sword_pivot(f)
            sw = f"{304 + f} {hand[0] - pv[0]} {hand[1] - pv[1]}"
            body = f"{200 + 4 * D.POSE_SWING + f} {bx} {by}"
            head = f"{100 + f} {hx} {hy}"
            rows.append(", ".join([f"0 {sx} {sy}", sw, body, head] if f == 0 else [f"0 {sx} {sy}", body, head, sw]))
        steps.append((rows, ["PLAYSOUND swordon.wav 1.5 2"] if k == 0 else []))
    return gani("spin.gani: the spin attack, one turn clockwise", [D.POSE_SWING], steps,
                extra=sprites, setback="idle")


def hidden_rows(bob):
    rows = []
    for dr in range(D.DIRS):
        (sx, sy), _, _ = D.OFFSETS[dr]
        rows.append(f"0 {sx} {sy}, 30 8 {6 + bob}")
    return rows


def hiddenstill_gani():
    return gani("hiddenstill.gani: standing still under a bush (1 step)", [], [(hidden_rows(0), [])], extra=[BUSH])


def hidden_gani():
    steps = [(hidden_rows(int(round(1 + math.cos(math.pi * k / 2)))), ["PLAYSOUND steps2.wav 1.5 2"] if k in (0, 4) else [])
             for k in range(8)]
    return gani("hidden.gani: walking under a bush, the bush bobbing", [], steps, ["LOOP", "CONTINUOUS"], extra=[BUSH])


EXTRA_GANIS = {
    "push": push_gani, "pull": pull_gani, "grab": grab_gani, "lift": lift_gani,
    "spin": spin_gani, "hidden": hidden_gani, "hiddenstill": hiddenstill_gani,
}


