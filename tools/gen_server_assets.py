def shifted(pal, names, hue=0.0, sat=1.0, val=1.0):
    """A copy of a Pal with the named entries moved in HSV."""
    q = D.Pal()
    q.names = list(pal.names)
    q.rgb = list(pal.rgb)
    for n in names:
        i = q.names.index(n)
        r, g, b = (c / 255 for c in q.rgb[i])
        h, s, v = colorsys.rgb_to_hsv(r, g, b)
        r, g, b = colorsys.hsv_to_rgb((h + hue) % 1.0, min(1.0, s * sat), min(1.0, v * val))
        q.rgb[i] = (round(r * 255), round(g * 255), round(b * 255))
    return q


