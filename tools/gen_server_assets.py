#!/usr/bin/env python3
"""Generate the Seihai server art pack (assets/server/).

A lab or community server that real clients log in to has to serve the
client's base art, because the 4.x to 6.x builds bundle none of it and ask
for it at login (Graal_analysis `client-internals/v5v6-expiry-and-black-screen.md`,
`protocol/v5v6-lab-play.md`, `client-internals/hud-603r7-black-box.md`).
Without it a real 5.24r4 or 6.03r7 draws a black screen. Until now the only
fix was to copy the art of a Graal 2.22 install into the world, which cannot
go in a repository.

This pack is the same idea built from Seihai's own art: everything in it is
drawn or synthesised by `tools/gen_default_assets.py` and this script, from
primitives, with no file of any Graal client or world read. It covers every
file name the lab captures show a 2.x to 6.x client asking for at login and in
ordinary play, so a world folder with this pack copied in draws on a real
client. The file names and image sizes follow the real ones; the art is ours.

The fonts are the one exception: they are Liberation Sans (SIL OFL 1.1),
copied unchanged under the file names the clients ask for (see
assets/server/fonts/README.md). They are not regenerated by this script.

Usage (from the repository root, Python 3.9+, Pillow):

    python3 tools/gen_server_assets.py            # write assets/server/
    python3 tools/gen_server_assets.py --check    # exit 1 if it differs
    python3 tools/gen_server_assets.py --fonts /usr/share/fonts/truetype/liberation
                                                  # also (re)copy the fonts

Deterministic: every random choice comes from a fixed seed.
"""
